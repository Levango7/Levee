// TestEndpointTableMatchesTheServedRoutes is the two-directional guard
// described in the file's leading comment.
func TestEndpointTableMatchesTheServedRoutes(t *testing.T) {
	table := endpointTableSection(t)

	tableRows := 0
	tableRoutes := make(map[string]bool)
	for _, line := range strings.Split(table, "\n") {
		m := rowRE.FindStringSubmatch(strings.TrimSpace(line))
		if m == nil {
			continue
		}
		route := m[1] + " " + m[2]
		tableRows++
		assert.False(t, tableRoutes[route],
			"§13.2 lists %s twice — one of the rows is stale", route)
		tableRoutes[route] = true
	}

	// Non-vacuity floor. The real table is well past this; a truncated or
	// relocated section must not read as "the table only has a few rows".
	require.Greater(t, tableRows, 40,
		"the §13.2 table parsed suspiciously few rows; the section markers or the row shape changed")

	// Direction 1: served but undocumented.
	for route, src := range documentedRoutes {
		if !tableRoutes[route] {
			t.Errorf("%s is served (%s) but missing from the §13.2 table — add the row to docs/levee-api.md", route, src)
		}
	}

	// Direction 2: documented but unserved.
	for route := range tableRoutes {
		if _, ok := documentedRoutes[route]; !ok {
			t.Errorf("§13.2 documents %s, which is not a route this gateway serves — "+
				"either the row is stale or a new route needs a handler AND an entry in documentedRoutes", route)
		}
	}
}

// nonResourceFamilies holds documented paths whose family is NOT dispatched by
// restResourceHandlers, each with the reason. An exception table with a
// reason beats a comment that claims the family is covered: a new entry forces
// the editor to say why, and a reason that stopped being true is easier to
// spot than a silent gap.
//
//   - chatops: each configured bot mounts its own public route at serve time
//     via gw.SetPublicRoute (cmd/levee/cmd_serve_chatops.go), so a freshly
//     constructed Gateway has none and restResourceHandlers cannot see it. The
//     route authenticates by the platform MAC, not the bearer gate — see
//     docs/levee-api.md §13.8.
var nonResourceFamilies = map[string]string{
	"chatops": "public routes registered per configured bot at serve time (SetPublicRoute, cmd/levee/cmd_serve_chatops.go); MAC-authenticated, bearer-exempt — §13.8",
}

// TestEndpointTableFamiliesAreDispatchable pins each documented path's family
// to the gateway's own route table. A typo in the docs ("/syste/status") would
// otherwise satisfy the row-parsing test while naming a family the server
// cannot dispatch; restResourceHandlers is the code's answer to "which
// families exist", so this reads it instead of a second hand-written list.
func TestEndpointTableFamiliesAreDispatchable(t *testing.T) {
	table := endpointTableSection(t)
	gw := NewGateway(ServeGatewayConfig{})
	families := gw.restResourceHandlers()

	for _, line := range strings.Split(table, "\n") {
		m := rowRE.FindStringSubmatch(strings.TrimSpace(line))
		if m == nil {
			continue
		}
		path := m[2]
		if !strings.HasPrefix(path, "/") || len(path) <= 1 {
			continue
		}
		family := strings.SplitN(strings.TrimPrefix(path, "/"), "/", 2)[0]
		normalised := strings.TrimSuffix(family, ":id")
		if reason, exempt := nonResourceFamilies[normalised]; exempt {
			// An exemption must be justified, not merely present: a stale
			// reason is exactly what this table exists to expose.
			assert.NotEmpty(t, strings.TrimSpace(reason),
				"family %q is in nonResourceFamilies with an empty reason", normalised)
			continue
		}
		_, ok := families[normalised]
		assert.True(t, ok,
			"§13.2 documents %s but the gateway dispatches no %q family (restResourceHandlers has %s)",
			path, normalised, familyKeys(families))
	}
}

// familyKeys renders the registered families for the failure message, so a
// reader does not have to open the source to see what the server does serve.
func familyKeys(families map[string]func(http.ResponseWriter, *http.Request, string, string)) string {
	keys := make([]string, 0, len(families))
	for k := range families {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return strings.Join(keys, ", ")
}

// endpointTableSection returns the §13.2 table as text, and fails loudly rather
// than returning an empty string when the markers move (an empty section would
// make every assertion pass).
func endpointTableSection(t *testing.T) string {
	t.Helper()
	body := readRepoDoc(t, "docs/levee-api.md")
	m := tableSectionRE.FindString(body)
	require.NotEmpty(t, m,
		"the §13.2 endpoint table section was not found in docs/levee-api.md — the heading or its terminator moved")
	return m
}

// readRepoDoc reads a file from the module root, walking up from the test's
// working directory the same way internal/chatops' producer guard does.
func readRepoDoc(t *testing.T, rel string) string {
	t.Helper()
	dir, err := os.Getwd()
	require.NoError(t, err)
	for i := 0; i < 10; i++ {
		internalOK := false
		if st, serr := os.Stat(filepath.Join(dir, "internal")); serr == nil && st.IsDir() {
			internalOK = true
		}
		cmdOK := false
		if st, serr := os.Stat(filepath.Join(dir, "cmd")); serr == nil && st.IsDir() {
			cmdOK = true
		}
		if internalOK && cmdOK {
			b, rerr := os.ReadFile(filepath.Join(dir, filepath.FromSlash(rel)))
			require.NoError(t, rerr, "%s must be readable from the module root", rel)
			return string(b)
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			break
		}
		dir = parent
	}
	t.Fatalf("cannot locate the module root (a directory holding internal/ and cmd/)")
	return ""
}

// TestDocumentedRoutesAreWellFormed is a cheap structural check on the ledger
// itself: the map is only useful if its keys stay "METHOD /path" and every
// path is absolute, because that is exactly the shape the table's rows use.
func TestDocumentedRoutesAreWellFormed(t *testing.T) {
	for route := range documentedRoutes {
		parts := strings.SplitN(route, " ", 2)
		require.Len(t, parts, 2, "route %q must be \"METHOD /path\"", route)
		switch parts[0] {
		case "GET", "POST", "PUT", "DELETE", "PATCH":
		default:
			t.Errorf("route %q uses method %q, which the table regexp does not parse", route, parts[0])
		}
		require.True(t, strings.HasPrefix(parts[1], "/"),
			"route %q must be an absolute path", route)
	}
	// Every entry must name where it is served: a route with an empty source
	// is one nobody can locate when it needs updating.
	for route, src := range documentedRoutes {
		require.NotEmpty(t, strings.TrimSpace(src),
			"route %q has no handler location in the ledger", route)
	}
}
