// rest_endpoint_table_test.go keeps docs/levee-api.md's endpoint table (§13.2)
// honest about the routes the gateway actually serves.
//
// Why this exists: the table is the only document that lists the REST surface,
// and it had drifted silently — the inventory tree (`/groups`, `/targets/import`,
// `/targets/:id/{status,history}`), three `/system` read routes (`batch-status`,
// `change-trend`, `takeover-events`) and the whole `/agents` tree were all served
// by the gateway while absent from the table. Nobody noticed because nothing
// reads the table: the CLI's flags are guarded by a cross-path test
// (cmd/levee/cli_reference_flags_test.go), the vocabulary is generated by
// docgen, and every other docs/ claim that turned into a lie in this repository
// (StatusExpired, --local authz, runToPB's Label, EventStateChange, the
// monitor's "no SSE route") was caught by a person, not by a test.
//
// What is asserted, in both directions:
//
//   - every route in `documentedRoutes` must appear in the table (a route that
//     exists only in code is invisible to every caller who reads the docs);
//   - every row in the table must be one of those routes (a path invented in
//     the docs would otherwise be scraped by an integration that trusted it);
//   - each documented path's first segment must be a family the gateway's own
//     route table registers (so a typo in the table cannot masquerade as a
//     family the server does not dispatch).
//
// Adding a route therefore means editing this map AND the table in the same
// change; the map's comment column names the file that serves it, so the edit
// is a two-line job rather than an archaeology project. Removing a route makes
// the same two places red together.
package grpc

