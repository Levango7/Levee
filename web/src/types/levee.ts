// Type definitions mirroring the LEVEE protobuf messages. Kept in sync with
// proto/levee.proto so the frontend gets static typing without generating
// TypeScript from the .proto file (which would require an extra build step).
//
// Value vocabularies are NOT declared here any more: every one with a Go owner is
// generated into ./vocabulary.ts by internal/docgen and re-exported below, so this
// file keeps one copy rather than two. Adding a status therefore means adding it
// to the owner's order list (internal/state, internal/cluster, internal/runstatus,
// internal/conversation, internal/approval) and running the generator — a hand copy
// here fails the generated-file comparison in internal/docgen, and a constant
// declared without joining its owner's list fails that package's
// vocabulary_ownership_test.go.
//
// Two of the re-exported names describe columns that share prose but not values:
// RunApprovalStatus is runs.approval_status, ApprovalStatus is the approvals
// table's own status. They are two tables on purpose; merging them would let one
// column be rendered against a set it can never hold.

import type { ApprovalStatus, ChangeStatus, PlanState, Priority, RunApprovalStatus, StepStatus, ApprovalLevel, ExecutionVerdict, RollbackStrategy } from './vocabulary'

export type { ApprovalStatus, ChangeStatus, PlanState, Priority, RunApprovalStatus, StepStatus, ApprovalLevel, ExecutionVerdict, RollbackStrategy }

export interface Change {
  id: string
  label: string
  status: ChangeStatus
  priority: Priority
  workflowFile: string
  templateName: string
  params: Record<string, string>
  createdAt: string | number
  updatedAt: string | number
  createdBy: string
  requester?: string
  team: string
  environment: string
  // Present only when the fetch asked for it (`?includePlan=true`) AND the run
  // has a stored plan; the server answers with no plan rather than an error when
  // there is none, so "no plan yet" stays a readable state instead of a failure.
  plan?: Plan
}

export interface Batch {
  index: number
  hosts: string[]
  maxConcurrency: number
}

// The plan as the gateway actually serialises it. Three names the proto declares
// are deliberately absent because nothing sends them: `waitAfter` (Batch),
// `estimatedDuration` and `potentialConflicts` (Plan) have zero writers in Go —
// not in the converters, not in the services, not in the tests — so protojson
// omits them from every response. Declaring them as required promised a value
// that could only ever read back `undefined`, and every consumer would have had
// to invent a default. If the gateway starts sending them, the wire contract
// (web/src/api/__contract__/wire.json, regenerated by
// internal/grpc/wire_snapshot_test.go) gains the key and
// web/src/api/wireContract.spec.ts fails until they are declared here again.
export interface Plan {
  changeId: string
  targetHosts: string[]
  batches: Batch[]
  impactSummary: string
}

export interface Target {
  id: string
  hostname: string
  channelType: 'ssh' | 'winrm'
  port: number
  credentialRef: string
  labels: Record<string, string>
  reachable: boolean
  /** Host group this target belongs to (inventory_groups). Empty = ungrouped.
   *  snake_case on the wire: proto Target.group_id, carried since the group
   *  tree landed — the stored row always had it, the wire did not. */
  groupId?: string
}

export interface Template {
  name: string
  description: string
  workflowContent: string
  requiredParams: string[]
  createdAt: string | number
  updatedAt: string | number
}

export interface TraceEntry {
  id: string
  runId: string
  action: string
  targetHost: string
  input: string
  output: string
  durationMs: number
  timestamp: string | number
  prevHash: string
  currHash: string
  // actor is populated by the audit log for approval/reject events; not present in raw TraceEntry proto.
  actor?: string
  // detail provides additional context for audit events (e.g. approval comment).
  detail?: string
}

export interface LogEntry {
  runId: string
  timestamp: string
  level: 'DEBUG' | 'INFO' | 'WARN' | 'ERROR'
  message: string
  source: string
}

export interface ChangeEvent {
  changeId: string
  eventType: string
  oldStatus: string
  newStatus: string
  message: string
  timestamp: string | number
}

export interface VersionInfo {
  version: string
  gitCommit: string
  buildDate: string
  goVersion: string
}

export interface SystemStatus {
  status: 'healthy' | 'degraded' | 'unhealthy'
  activeRuns: number
  pausedRuns: number
  uptimeSeconds: number
  storeType: string
  warnings: string[]
  /**
   * 控制面数据库本次探测是否可达。false 表示平台处于分区期（断网策略 Q3）。
   * 读面仍然回答，但**不得**把读不到说成「没有」。
   */
  controlPlaneReachable?: boolean
  /** activeRuns / pausedRuns 是否来自一次新鲜读取。false 时这两个数字是「未知」，不是 0。 */
  runCountsAvailable?: boolean
  /** 分区原因（不可达时给出探测错误原文）。 */
  partitionReason?: string
}

export interface PageResult<T> {
  items: T[]
  nextPageToken: string
  totalSize: number
}

// AuditPageResult mirrors the RAW audit API response shape where the proto
// field is "entries" not "items". The api layer normalizes this into
// PageResult<T> before views see it, so only the raw envelope uses this type.
export interface AuditPageResult<T> {
  entries: T[]
  nextPageToken: string
  totalSize: number
}



// ============================================================
// DB Change Ticket (全链视图) — 对应 proto/levee.proto DBChangeTicket
// ============================================================

// PlanState, ApprovalLevel, ExecutionVerdict, RollbackStrategy are re-exported
// from ./vocabulary (generated by internal/docgen from Go vocabularies).
// ApprovalStatusType uses the approval-record status vocabulary (ApprovalStatus).

/** 变更基础信息 */
export interface ChangeSection {
  id: string
  label: string
  status: ChangeStatus
  priority: Priority
  environment: string
  creator: string
  workflowFile: string
  templateName: string
  planHash: string
  planState: PlanState
  createdAt: string | number
  updatedAt: string | number
}

/** SQL 审核与步骤 */
export interface SQLSection {
  hasSql: boolean
  steps: SQLStep[]
  review?: SQLReviewSummary
}

/** 单条 SQL 步骤 */
export interface SQLStep {
  step: string
  sql: string
  batchNo: number
  hostCount: number
}

/** SQL 审核汇总 */
export interface SQLReviewSummary {
  verdict: 'pass' | 'warn' | 'fail'
  score: number
  findings: SQLReviewFinding[]
  reviewedAt: string | number
  reviewer: string
}

/** 单条审核发现 */
export interface SQLReviewFinding {
  ruleId: string
  ruleName: string
  severity: 'pass' | 'warn' | 'fail'  // protojson: pass/warn/fail from SQLReviewVerdict
  message: string
  line?: number
  column?: number
  sqlSnippet?: string
}

/** 回滚方案 */
export interface RollbackSection {
  strategy: RollbackStrategy
  onFailure: string
  verifyAfter: boolean
  snapshotPaths: string[]
  stepUndos: StepUndo[]
  hasUndo: boolean
}

/** 步骤级回滚动作 */
export interface StepUndo {
  stepName: string
  action: string
  params: Record<string, string>
}

/** 变更窗口 */
export interface WindowSection {
  enforcedAt: string | number
  persistedPerRun: boolean
  note: string
}

/** 审批链 */
export interface ApprovalSection {
  hasApproval: boolean
  level: ApprovalLevel
  status: ApprovalStatus
  approvers: string[]
  minApprovers: number
  decisions: ApprovalDecisionItem[]
  matchesPlan: boolean
  legacyApproval: boolean
  staleApproval: boolean
  planHash: string
  initiator: string
  excludeInitiator: boolean
  expiresAt: string | number
}

/** 单条审批决策 */
export interface ApprovalDecisionItem {
  approver: string
  action: 'approve' | 'reject'
  reason: string
  decidedAt: string | number
}

/** 执行证据 */
export interface ExecutionSection {
  verdict: ExecutionVerdict
  hasEvidence: boolean
  evidence: ExecutionEvidenceItem[]
}

/** 单条执行证据 */
export interface ExecutionEvidenceItem {
  host: string
  batchNo: number
  stepName: string
  status: string
  startedAt: string | number
  finishedAt: string | number
  output: string
  exitCode?: number
}

/** 审计验证 */
export interface AuditSection {
  verified: boolean
  unverifiable: boolean
  verifyError: string
  traces: TraceEntry[]
}

/** 完整发布单 */
export interface DBChangeTicket {
  change: ChangeSection
  sql: SQLSection
  rollback: RollbackSection
  window: WindowSection
  approval: ApprovalSection
  execution: ExecutionSection
  audit: AuditSection
}

/** 获取发布单请求 */
export interface GetDBChangeTicketRequest {
  changeId: string
}

/** 获取发布单响应 */
export interface GetDBChangeTicketResponse {
  ticket: DBChangeTicket
}

export interface ApiError {
  code: number
  message: string
  details?: unknown
}