// Type definitions mirroring the LEVEE protobuf messages. Kept in sync with
// proto/levee.proto so the frontend gets static typing without generating
// TypeScript from the .proto file (which would require an extra build step).
//
// The two vocabularies that have Go owners (run status, priority) are NOT
// declared here any more: they are generated into ./vocabulary.ts by
// internal/docgen and re-exported below, so this file keeps one copy rather
// than two. Adding a status therefore means adding it in internal/runstatus and
// running the generator — a hand-copy here would fail
// internal/runstatus/vocabulary_guard_test.go.

import type { ChangeStatus, Priority } from './vocabulary'

export type { ChangeStatus, Priority }

export interface Change {
  id: string
  label: string
  status: ChangeStatus
  priority: Priority
  workflowFile: string
  templateName: string
  params: Record<string, string>
  createdAt: number
  updatedAt: number
  createdBy: string
  requester?: string
  team: string
  environment: string
  // Present only when the fetch asked for it (`?includePlan=true`) AND the run
  // has a stored plan; the server answers with no plan rather than an error when
  // there is none, so "no plan yet" stays a readable state instead of a failure.
  plan?: Plan
}

export interface Batch {
  index: number
  hosts: string[]
  maxConcurrency: number
}

// The plan as the gateway actually serialises it. Three names the proto declares
// are deliberately absent because nothing sends them: `waitAfter` (Batch),
// `estimatedDuration` and `potentialConflicts` (Plan) have zero writers in Go —
// not in the converters, not in the services, not in the tests — so protojson
// omits them from every response. Declaring them as required promised a value
// that could only ever read back `undefined`, and every consumer would have had
// to invent a default. If the gateway starts sending them, the wire contract
// (web/src/api/__contract__/wire.json, regenerated by
// internal/grpc/wire_snapshot_test.go) gains the key and
// web/src/api/wireContract.spec.ts fails until they are declared here again.
export interface Plan {
  changeId: string
  targetHosts: string[]
  batches: Batch[]
  impactSummary: string
}

export interface Target {
  id: string
  hostname: string
  channelType: 'ssh' | 'winrm'
  port: number
  credentialRef: string
  labels: Record<string, string>
  reachable: boolean
}

export interface Template {
  name: string
  description: string
  workflowContent: string
  requiredParams: string[]
  createdAt: number
  updatedAt: number
}

export interface TraceEntry {
  id: string
  runId: string
  action: string
  targetHost: string
  input: string
  output: string
  durationMs: number
  timestamp: number
  prevHash: string
  currHash: string
  // actor is populated by the audit log for approval/reject events; not present in raw TraceEntry proto.
  actor?: string
  // detail provides additional context for audit events (e.g. approval comment).
  detail?: string
}

export interface LogEntry {
  runId: string
  timestamp: string
  level: 'DEBUG' | 'INFO' | 'WARN' | 'ERROR'
  message: string
  source: string
}

export interface ChangeEvent {
  changeId: string
  eventType: string
  oldStatus: string
  newStatus: string
  message: string
  timestamp: number
}

export interface VersionInfo {
  version: string
  gitCommit: string
  buildDate: string
  goVersion: string
}

export interface SystemStatus {
  status: 'healthy' | 'degraded' | 'unhealthy'
  activeRuns: number
  pausedRuns: number
  uptimeSeconds: number
  storeType: string
  warnings: string[]
}

export interface PageResult<T> {
  items: T[]
  nextPageToken: string
  totalSize: number
}

// AuditPageResult mirrors the RAW audit API response shape where the proto
// field is "entries" not "items". The api layer normalizes this into
// PageResult<T> before views see it, so only the raw envelope uses this type.
export interface AuditPageResult<T> {
  entries: T[]
  nextPageToken: string
  totalSize: number
}

export interface ApiError {
  code: number
  message: string
  details?: unknown
}